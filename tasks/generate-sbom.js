#!/usr/bin/env node

const fs = require("node:fs")
const path = require("node:path")
const { execFileSync } = require("node:child_process")

const SBOM_NAME = "fontara-production-dependencies.cdx.json"
const MAX_SBOM_BYTES = 5 * 1024 * 1024

function validateSbom(bom, pkg) {
  const root = bom?.metadata?.component
  if (
    bom?.bomFormat !== "CycloneDX" ||
    bom.specVersion !== "1.6" ||
    root?.type !== "application" ||
    root.name !== pkg.name ||
    root.version !== pkg.version ||
    typeof root["bom-ref"] !== "string" ||
    !Array.isArray(bom.components) ||
    !Array.isArray(bom.dependencies)
  )
    throw new Error("Production inventory format or package identity mismatch.")
  const refs = new Set([root["bom-ref"]])
  for (const component of bom.components) {
    if (
      !component.name ||
      !component.version ||
      typeof component["bom-ref"] !== "string" ||
      refs.has(component["bom-ref"])
    )
      throw new Error("Production inventory has an invalid component identity.")
    refs.add(component["bom-ref"])
  }
  const graph = new Map()
  for (const dependency of bom.dependencies) {
    if (
      !refs.has(dependency.ref) ||
      graph.has(dependency.ref) ||
      !Array.isArray(dependency.dependsOn) ||
      dependency.dependsOn.some((ref) => !refs.has(ref))
    )
      throw new Error("Production inventory has an invalid dependency graph.")
    graph.set(dependency.ref, dependency.dependsOn)
  }
  if (!graph.has(root["bom-ref"]))
    throw new Error(
      "Production inventory is missing its root dependency graph."
    )
  const direct = new Set(graph.get(root["bom-ref"]) || [])
  for (const name of Object.keys({
    ...pkg.dependencies,
    ...pkg.optionalDependencies
  })) {
    if (
      !bom.components.some(
        (component) =>
          (component.group
            ? `${component.group}/${component.name}`
            : component.name) === name && direct.has(component["bom-ref"])
      )
    )
      throw new Error(
        `Production inventory is missing direct dependency: ${name}`
      )
  }
  return bom
}

// Canonical object keys plus dependency-set ordering make output reproducible;
// optional document UUID/timestamp do not describe the installed dependencies.
function normalizeSbom(raw, pkg) {
  const bom = validateSbom(JSON.parse(raw), pkg)
  const tool = bom.metadata.tools?.components?.find(
    (component) => component.name === "pnpm"
  )
  if (`pnpm@${tool?.version}` !== pkg.packageManager)
    throw new Error(
      "Production inventory was generated by an unexpected pnpm version."
    )
  delete bom.serialNumber
  delete bom.metadata.timestamp
  bom.components.sort((a, b) => a["bom-ref"].localeCompare(b["bom-ref"], "en"))
  bom.dependencies.sort((a, b) => a.ref.localeCompare(b.ref, "en"))
  for (const dependency of bom.dependencies)
    dependency.dependsOn.sort((a, b) => a.localeCompare(b, "en"))
  const canonical = (value) => {
    if (Array.isArray(value)) return value.map(canonical)
    if (value && typeof value === "object")
      return Object.fromEntries(
        Object.keys(value)
          .sort()
          .map((key) => [key, canonical(value[key])])
      )
    return value
  }
  return `${JSON.stringify(canonical(bom), null, 2)}\n`
}

function generateSbom({ directory = process.cwd(), run = execFileSync } = {}) {
  const pkg = JSON.parse(
    fs.readFileSync(path.join(directory, "package.json"), "utf8")
  )
  const raw = run(
    "pnpm",
    [
      "sbom",
      "--sbom-format",
      "cyclonedx",
      "--sbom-spec-version",
      "1.6",
      "--prod",
      "--sbom-type",
      "application",
      "--lockfile-only"
    ],
    {
      cwd: directory,
      encoding: "utf8",
      timeout: 120000,
      maxBuffer: MAX_SBOM_BYTES,
      stdio: ["ignore", "pipe", "pipe"]
    }
  )
  const bytes = normalizeSbom(raw, pkg)
  const output = path.join(directory, "build", SBOM_NAME)
  fs.mkdirSync(path.dirname(output), { recursive: true })
  fs.writeFileSync(output, bytes)
  return output
}

module.exports = {
  SBOM_NAME,
  MAX_SBOM_BYTES,
  validateSbom,
  normalizeSbom,
  generateSbom
}

if (require.main === module) {
  try {
    console.log(`Generated production dependency inventory: ${generateSbom()}`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
